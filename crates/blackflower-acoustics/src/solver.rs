const MAX_PORTAL_ROUTE_EXPANSIONS: usize = 1_000_000;

/// Fixed-capacity release profile for one authoritative acoustic world.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AcousticWorldSettings {
    /// Maximum receivers active in a tick.
    pub max_receivers: usize,
    /// Maximum newly captured emissions in a tick.
    pub max_active_emissions: usize,
    /// Maximum candidate source/receiver pairs resolved in a tick.
    pub max_candidate_pairs: usize,
    /// Maximum alternate zone paths retained per pair.
    pub max_paths_per_pair: usize,
    /// Maximum crossed surfaces resolved for transmission.
    pub max_transmission_surfaces: usize,
    /// Maximum simultaneously retained live voice frames for one client.
    pub max_client_voices: usize,
    /// Maximum retained transient observations across the AI interval.
    pub max_recent_observations: usize,
}

impl Default for AcousticWorldSettings {
    fn default() -> Self {
        Self {
            max_receivers: 96,
            max_active_emissions: 512,
            max_candidate_pairs: 4_096,
            max_paths_per_pair: 4,
            max_transmission_surfaces: 8,
            max_client_voices: 128,
            max_recent_observations: 16_384,
        }
    }
}

/// Complete facts and gated deliveries generated by one acoustic tick.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AcousticFrame {
    /// Structure revision used for every solve in this frame.
    pub structure_version: AcousticStructureVersion,
    /// New bot observations created by emissions captured this tick.
    pub observations: Vec<AcousticObservation>,
    /// Gated non-voice deliveries.
    pub sounds: Vec<AudibleSoundDelivery>,
    /// Gated exact-Opus voice deliveries.
    pub voices: Vec<AudibleVoiceDelivery>,
    /// Number of direct/transmission pairs preserved regardless of indirect budget.
    pub direct_pairs: usize,
    /// Number of source/receiver pairs receiving indirect path refinement.
    pub candidate_pairs: usize,
    /// Number of pairs omitted when the deterministic pair budget was exhausted.
    pub deferred_indirect_pairs: usize,
}

/// Replay-safe source envelope without PCM, Opus, position, or entity identity.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AcousticReplayEmission {
    /// Physical sound class.
    pub class: crate::SoundClass,
    /// Source sample on the authoritative timeline.
    pub start_sample: u64,
    /// Authored/calibrated source level.
    pub reference_spl_db_q8: i32,
    /// Quantized source envelope for this tick.
    pub bands: BandEnergy,
}

/// Replay-safe delivery fact; voice contains no stream, sequence, payload, or identity.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AcousticReplayDelivery {
    /// Non-voice client event delivery.
    Sound {
        /// Recipient ID owned by replay routing.
        receiver_id: u32,
        /// Public client event ID.
        client_event_id: u32,
        /// Authoritative path parameters.
        propagation: PropagationDescriptor,
    },
    /// Physical voice audibility fact without conversation data.
    Voice {
        /// Recipient ID owned by replay routing.
        receiver_id: u32,
        /// Authoritative path parameters.
        propagation: PropagationDescriptor,
    },
}

/// Facts retained for deterministic replay without recorded conversation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AcousticReplayFacts {
    /// Structure revision used by all facts.
    pub structure_version: AcousticStructureVersion,
    /// Source envelopes captured this tick.
    pub emissions: Vec<AcousticReplayEmission>,
    /// Privacy-preserving bot observations.
    pub observations: Vec<AcousticObservation>,
    /// Gated delivery facts with voice payloads deliberately erased.
    pub deliveries: Vec<AcousticReplayDelivery>,
}

impl AcousticReplayFacts {
    fn with_capacity(settings: AcousticWorldSettings, max_direct_pairs: usize) -> Self {
        Self {
            structure_version: AcousticStructureVersion(1),
            emissions: Vec::with_capacity(settings.max_active_emissions),
            observations: Vec::with_capacity(max_direct_pairs),
            deliveries: Vec::with_capacity(max_direct_pairs),
        }
    }

    fn clear(&mut self, version: AcousticStructureVersion) {
        self.structure_version = version;
        self.emissions.clear();
        self.observations.clear();
        self.deliveries.clear();
    }
}

impl AcousticFrame {
    fn with_capacity(settings: AcousticWorldSettings, max_direct_pairs: usize) -> Self {
        Self {
            structure_version: AcousticStructureVersion(1),
            observations: Vec::with_capacity(max_direct_pairs),
            sounds: Vec::with_capacity(max_direct_pairs),
            voices: Vec::with_capacity(settings.max_candidate_pairs),
            direct_pairs: 0,
            candidate_pairs: 0,
            deferred_indirect_pairs: 0,
        }
    }

    fn clear(&mut self, version: AcousticStructureVersion) {
        self.structure_version = version;
        self.observations.clear();
        self.sounds.clear();
        self.voices.clear();
        self.direct_pairs = 0;
        self.candidate_pairs = 0;
        self.deferred_indirect_pairs = 0;
    }
}

